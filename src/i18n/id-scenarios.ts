// Teks skenario: pemilih, panel langkah, Cari Gangguan, dan ringkasan nilai; digabung ke `id`.
const number = (value: number, digits = 0): string =>
  value.toLocaleString('id-ID', { minimumFractionDigits: digits, maximumFractionDigits: digits });

const clock = (seconds: number): string => {
  const total = Math.max(0, Math.round(seconds));
  const two = (value: number) => String(value).padStart(2, '0');
  const hours = Math.floor(total / 3600);
  const rest = `${two(Math.floor((total % 3600) / 60))}:${two(total % 60)}`;
  return hours > 0 ? `${hours}:${rest}` : rest;
};

